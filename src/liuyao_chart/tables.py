def _palace_table() -> dict[str, tuple[str, str, int]]:
    result: dict[str, tuple[str, str, int]] = {}
    for palace, trigram_bits in TRIGRAM_BITS.items():
        base = trigram_bits * 2
        for flips, shi, palace_type in FLIP_SEQUENCE:
            bits = "".join(str(1 - int(bit)) if i in flips else bit for i, bit in enumerate(base))
            result[bits] = (palace, palace_type, shi)
    return result


PALACE_TABLE = _palace_table()
